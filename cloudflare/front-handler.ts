// The routing half of the OpenNext Worker, with the Next server in another Worker.
//
// `opennextjs-cloudflare build` generates .open-next/worker.js, which runs the
// routing layer (the "middleware": proxy.ts, rewrites, the cache interception
// that answers fully cached pages) and, when that layer does not answer, loads
// the Next server with a dynamic import. Both end up in one 57 MiB script, and
// every new isolate pays to start all of it (1.3–2.6 s before the first byte),
// even when the cache answers the request.
//
// This is the same handler, line for line, except for the last step: what the
// routing layer does not answer goes to the Next server Worker over the
// NEXT_SERVER service binding (cloudflare/next-server.ts). The routing layer
// already hands its result to the server as a request with internal headers
// (resolved routes, initial URL), the way OpenNext runs an external middleware,
// so nothing else changes. That Worker has no public URL; only this one calls it.
//
// Keep in step with node_modules/@opennextjs/cloudflare/dist/cli/templates/worker.js.

// @ts-expect-error -- generated by `opennextjs-cloudflare build`
import { handleCdnCgiImageRequest, handleImageRequest } from "../.open-next/cloudflare/images.js";
// @ts-expect-error -- generated by `opennextjs-cloudflare build`
import { runWithCloudflareRequestContext } from "../.open-next/cloudflare/init.js";
// @ts-expect-error -- generated by `opennextjs-cloudflare build`
import { maybeGetSkewProtectionResponse } from "../.open-next/cloudflare/skew-protection.js";
// @ts-expect-error -- generated by `opennextjs-cloudflare build`
import { handler as middlewareHandler } from "../.open-next/middleware/handler.mjs";

type Fetcher = { fetch(request: Request): Promise<Response> };
type FrontEnv = { NEXT_SERVER: Fetcher };
type Context = { waitUntil(promise: Promise<unknown>): void };

declare global {
  // Set by .open-next/cloudflare/init.js from the Next config.
  var __NEXT_BASE_PATH__: string;
  var __TRAILING_SLASH__: boolean;
}

export default {
  async fetch(request: Request, env: FrontEnv, ctx: Context): Promise<Response> {
    return runWithCloudflareRequestContext(request, env, ctx, async () => {
      const skewResponse = maybeGetSkewProtectionResponse(request);
      if (skewResponse) return skewResponse;

      const url = new URL(request.url);
      if (url.pathname.startsWith("/cdn-cgi/image/")) {
        return handleCdnCgiImageRequest(url, env);
      }
      const imagePath = `${globalThis.__NEXT_BASE_PATH__}/_next/image${globalThis.__TRAILING_SLASH__ ? "/" : ""}`;
      if (url.pathname === imagePath) {
        return await handleImageRequest(url, request.headers, env);
      }

      const requestOrResponse: Request | Response = await middlewareHandler(request, env, ctx);
      if (requestOrResponse instanceof Response) return requestOrResponse;
      return env.NEXT_SERVER.fetch(requestOrResponse);
    });
  },
};
