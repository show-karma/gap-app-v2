#!/usr/bin/env node
// Writes .open-next/assets/_headers, the response headers Cloudflare's static
// asset server adds to the files it serves without running the Worker.
//
// Everything under /_next/static has a content hash in its path, so a file
// there never changes: browsers may keep it for a year without asking again,
// as Vercel tells them (`public, max-age=31536000, immutable`). Without this
// file the asset server answers `public, max-age=0, must-revalidate`, and every
// visit revalidates every JS and CSS chunk.
//
// Runs at the end of `pnpm cf:build`, after the Studio build has written its
// assets. Usage: node scripts/cf-asset-headers.mjs [assets dir]
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

export const ASSET_HEADERS = `# Generated by scripts/cf-asset-headers.mjs; do not edit.
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable
`;

function main() {
  const assetsDir = path.resolve(process.argv[2] ?? ".open-next/assets");
  if (!existsSync(path.join(assetsDir, "_next", "static"))) {
    throw new Error(`${assetsDir} has no _next/static: run opennextjs-cloudflare build first.`);
  }
  const file = path.join(assetsDir, "_headers");
  if (existsSync(file)) {
    throw new Error(`${file} already exists (public/_headers?); merge it into this script instead.`);
  }
  writeFileSync(file, ASSET_HEADERS);
  process.stdout.write(`Wrote ${path.relative(process.cwd(), file)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
