#!/usr/bin/env node
// Writes wrangler.bootstrap.jsonc: the routing Worker config (wrangler.jsonc) of
// one environment, flattened, without its NEXT_SERVER binding. Used once, for
// the first deploy of a Worker pair (.github/workflows/cloudflare-production.yml).
//
//   node scripts/cf-bootstrap-config.mjs <env>
//
// The Next server Worker binds the routing Worker's Durable Objects by script
// name, so the routing Worker has to exist first; and the routing Worker's
// NEXT_SERVER service binding needs the Next server Worker to exist. The first
// version of the routing Worker therefore goes up without that binding, and the
// next deploy, with the real config, adds it.
import { writeFileSync } from "node:fs";
import { experimental_readRawConfig } from "wrangler";

const [envName] = process.argv.slice(2);
if (!/^[a-z][a-z0-9-]*$/.test(envName ?? "")) {
  process.stderr.write("Usage: cf-bootstrap-config.mjs <env>\n");
  process.exit(2);
}
const { rawConfig } = experimental_readRawConfig({ config: "wrangler.jsonc" });
const { env, ...topLevel } = rawConfig;
if (!env?.[envName]) throw new Error(`wrangler.jsonc has no env.${envName}`);
const config = { ...topLevel, ...env[envName] };
config.services = (config.services ?? []).filter((s) => s.binding !== "NEXT_SERVER");

writeFileSync(
  "wrangler.bootstrap.jsonc",
  `// Generated by scripts/cf-bootstrap-config.mjs; do not edit or commit.\n${JSON.stringify(config, null, 2)}\n`
);
process.stdout.write(`Bootstrap config for ${config.name}, without NEXT_SERVER\n`);
